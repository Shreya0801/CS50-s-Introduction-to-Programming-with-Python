players = ["Mario", "Luigi"]
print(players)

# to add items to list..
players.append("Arya")
print(players)

# to extend list...
players.extend(["Sansa","Jon","Theon"])
print(players)

# for removing items..
players.remove("Sansa")
print(players)

#for inserting at perticular index..
players.insert(1,"Sansa")
print(players)

#for reversing the list
players.reverse()
print(players)